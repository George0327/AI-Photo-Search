"""Measure face search quality against a labelled benchmark, with two ablations.

Input JSON (default: face_benchmark.json):
[
  {
    "person": "Person A",
    "album_ids": ["<driveFolderId>", ...],   # optional; empty = all face-indexed albums
    "appears_in": ["<driveFileId>", ...],     # ground truth: every photo they are in
    "references": ["<driveFileId>", ...]       # query photos (5 recommended)
  },
  ...
]

The reference photos are fetched from the gallery by id and uploaded to
POST /api/search/faces (multipart), exactly as the UI does.

Modes:
  (default)         per-identity Recall@k / Precision@k at the operating threshold,
                    plus the reference-count ablation (1 / 3 / 5 references).
  --threshold-sweep needs direct access to the AI service (the public API fixes the
                    threshold). Provide --ai-url and --internal-key; it requests with
                    threshold 0 and sweeps the cutoff locally to draw a PR curve.

Usage:
    python eval_faces.py [--benchmark face_benchmark.json] [--topk 100]
    python eval_faces.py --threshold-sweep --ai-url http://localhost:8000 \
                         --internal-key <AI_SERVICE_INTERNAL_API_KEY>
"""
from __future__ import annotations

import argparse
import csv
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import requests

import common

K_VALUES = (5, 10, 20)


def fetch_content(session, file_id: str) -> bytes:
    r = session.get(f"{common.BASE_URL}/api/drive/images/{file_id}/content",
                    timeout=common.TIMEOUT)
    r.raise_for_status()
    return r.content


def search_faces_public(session, images: list[bytes], album_ids: list[str],
                        topk: int) -> list[tuple[str, float]]:
    files = [("files", (f"ref{i}.jpg", b, "image/jpeg")) for i, b in enumerate(images)]
    data = [("topK", str(topk))] + [("albumIds", a) for a in album_ids]
    r = session.post(f"{common.BASE_URL}/api/search/faces", files=files, data=data,
                     timeout=common.TIMEOUT)
    r.raise_for_status()
    return [(res["file"]["id"], res["score"]) for res in r.json().get("results", [])]


def search_faces_direct(ai_url: str, key: str, images: list[bytes], album_ids: list[str],
                        topk: int, threshold: float) -> list[tuple[str, float]]:
    files = [("files", (f"ref{i}.jpg", b, "image/jpeg")) for i, b in enumerate(images)]
    data = [("top_k", str(topk)), ("threshold", str(threshold))]
    data += [("album_ids", a) for a in album_ids]
    r = requests.post(f"{ai_url.rstrip('/')}/search/faces", files=files, data=data,
                      headers={"X-Internal-API-Key": key}, timeout=common.TIMEOUT)
    r.raise_for_status()
    return [(res["item_id"], res["score"]) for res in r.json().get("results", [])]


# ── default mode: per-identity metrics + reference-count ablation ──────────────

def evaluate(session, benchmark: list[dict], topk: int) -> tuple[list[dict], dict]:
    rows = []
    ablation = {n: [] for n in (1, 3, 5)}  # ref-count -> list of recall@10
    for entry in benchmark:
        person = entry["person"]
        relevant = set(entry["appears_in"])
        album_ids = entry.get("album_ids", [])
        refs = entry["references"]
        ref_bytes = [fetch_content(session, fid) for fid in refs]

        retrieved = [fid for fid, _ in search_faces_public(session, ref_bytes, album_ids, topk)]
        row = {"person": person, "num_relevant": len(relevant), "num_retrieved": len(retrieved)}
        for k in K_VALUES:
            row[f"P@{k}"] = common.precision_at_k(retrieved, relevant, k)
            row[f"R@{k}"] = common.recall_at_k(retrieved, relevant, k)
        rows.append(row)
        print(f"  {person:>16}: R@10={row['R@10']:.2f} P@10={row['P@10']:.2f} "
              f"({len(relevant)} labelled)")

        # reference-count ablation (uses the same relevant set)
        for n in (1, 3, 5):
            if len(ref_bytes) >= n:
                sub = [fid for fid, _ in search_faces_public(session, ref_bytes[:n], album_ids, topk)]
                ablation[n].append(common.recall_at_k(sub, relevant, 10))
    ablation_mean = {n: common.mean(v) for n, v in ablation.items() if v}
    return rows, ablation_mean


def aggregate(rows: list[dict]) -> dict:
    keys = [f"{p}@{k}" for k in K_VALUES for p in ("P", "R")]
    return {k: common.mean(r[k] for r in rows) for k in keys}


def write_csv(rows: list[dict], path: str) -> None:
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def write_tex(rows: list[dict], overall: dict, path: str) -> None:
    lines = ["% auto-generated by eval/eval_faces.py",
             "\\begin{tabular}{|l|c|c|c|c|}",
             "\\hline",
             "\\textbf{Identity} & \\textbf{R@5} & \\textbf{R@10} & \\textbf{P@10} "
             "& \\textbf{labelled} \\\\ [0.5ex]", "\\hline"]
    for r in rows:
        lines.append(f"{r['person']} & {r['R@5']:.2f} & {r['R@10']:.2f} & "
                     f"{r['P@10']:.2f} & {r['num_relevant']} \\\\")
        lines.append("\\hline")
    lines.append(f"\\textbf{{Mean}} & {overall['R@5']:.2f} & {overall['R@10']:.2f} & "
                 f"{overall['P@10']:.2f} & -- \\\\")
    lines.append("\\hline")
    lines.append("\\end{tabular}")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def plot_ablation(ablation: dict, path: str) -> None:
    if not ablation:
        return
    ns = sorted(ablation)
    plt.figure(figsize=(5, 4))
    plt.bar([str(n) for n in ns], [ablation[n] for n in ns], width=0.5)
    plt.ylim(0, 1)
    plt.xlabel("number of reference photos")
    plt.ylabel("mean Recall@10")
    plt.title("Effect of reference count on face search")
    plt.tight_layout()
    plt.savefig(path)
    print(f"Wrote {path}")


# ── threshold sweep (direct AI) ────────────────────────────────────────────────

def threshold_sweep(session, benchmark: list[dict], ai_url: str, key: str, topk: int,
                    path: str) -> None:
    thresholds = np.linspace(0.0, 0.7, 36)
    precisions, recalls = [], []
    # collect (score, is_relevant) across all identities
    scored: list[tuple[float, bool, int]] = []  # (score, relevant, identity_relevant_count)
    per_identity_relevant = []
    for entry in benchmark:
        relevant = set(entry["appears_in"])
        per_identity_relevant.append(len(relevant))
        ref_bytes = [fetch_content(session, fid) for fid in entry["references"]]
        results = search_faces_direct(ai_url, key, ref_bytes, entry.get("album_ids", []),
                                      topk, threshold=0.0)
        for fid, score in results:
            scored.append((score, fid in relevant, len(relevant)))

    total_relevant = sum(per_identity_relevant)
    for t in thresholds:
        kept = [(rel) for score, rel, _ in scored if score >= t]
        tp = sum(1 for rel in kept if rel)
        fp = sum(1 for rel in kept if not rel)
        precisions.append(tp / (tp + fp) if (tp + fp) else 1.0)
        recalls.append(tp / total_relevant if total_relevant else 0.0)

    plt.figure(figsize=(5, 4))
    plt.plot(recalls, precisions, marker="o", ms=3)
    for t, rc, pr in zip(thresholds, recalls, precisions):
        if abs(t - 0.35) < 0.011:  # mark the operating point
            plt.scatter([rc], [pr], color="red", zorder=5)
            plt.annotate("t=0.35", (rc, pr), textcoords="offset points", xytext=(6, 6))
    plt.xlabel("recall")
    plt.ylabel("precision")
    plt.xlim(0, 1)
    plt.ylim(0, 1.05)
    plt.title("Face search: precision–recall vs similarity threshold")
    plt.tight_layout()
    plt.savefig(path)
    print(f"Wrote {path}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--benchmark", default="face_benchmark.json")
    ap.add_argument("--topk", type=int, default=100)
    ap.add_argument("--threshold-sweep", action="store_true")
    ap.add_argument("--ai-url", help="AI service base url for the threshold sweep")
    ap.add_argument("--internal-key", help="X-Internal-API-Key for the AI service")
    args = ap.parse_args()

    with open(args.benchmark, encoding="utf-8") as f:
        benchmark = json.load(f)

    session = common.make_session()
    common.require_auth(session)

    if args.threshold_sweep:
        if not (args.ai_url and args.internal_key):
            ap.error("--threshold-sweep needs --ai-url and --internal-key "
                     "(the public API fixes the threshold)")
        print("Running threshold sweep via the AI service ...")
        threshold_sweep(session, benchmark, args.ai_url, args.internal_key, args.topk,
                        os.path.join(common.figs_dir(), "face_threshold_pr.pdf"))
        return

    print(f"Evaluating {len(benchmark)} identities (topK={args.topk}) ...")
    rows, ablation = evaluate(session, benchmark, args.topk)
    overall = aggregate(rows)
    print("\n=== Mean over identities ===")
    for k in [f"{p}@{kk}" for kk in K_VALUES for p in ("P", "R")]:
        print(f"  {k:>6}: {overall[k]:.3f}")
    if ablation:
        print("  reference-count ablation (mean R@10):",
              {n: round(v, 3) for n, v in ablation.items()})

    write_csv(rows, os.path.join(common.out_dir(), "faces_per_identity.csv"))
    write_tex(rows, overall, os.path.join(common.out_dir(), "faces_metrics.tex"))
    plot_ablation(ablation, os.path.join(common.figs_dir(), "face_reference_count.pdf"))
    print(f"\nTables/CSV in {common.out_dir()}")


if __name__ == "__main__":
    main()
