"""Measure semantic (text) search quality against a labelled benchmark.

Input JSON (default: semantic_benchmark.json):
[
  {
    "query": "two people shaking hands on stage",
    "category": "activity",
    "album_ids": ["<driveFolderId>", ...],
    "relevant": ["<driveFileId>", ...]
  },
  ...
]

For each query it calls GET /api/search, takes the ranked driveFileIds, and scores
them against the relevant set. It reports Precision@5/@10, Recall@10, mAP, nDCG@10
and MRR, both overall and per category.

Usage:
    python eval_semantic.py [--benchmark semantic_benchmark.json] [--topk 50]

Outputs (into ./out and docs/Thesis/figs):
    semantic_per_query.csv     one row per query
    semantic_metrics.tex       aggregate + per-category LaTeX table
    semantic_by_category.pdf   per-category bar chart
"""
from __future__ import annotations

import argparse
import csv
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

import common

K_VALUES = (5, 10)


def run_query(session, query: str, album_ids: list[str], topk: int) -> list[str]:
    params = [("query", query), ("topK", str(topk))]
    params += [("albumIds", a) for a in album_ids]
    r = session.get(f"{common.BASE_URL}/api/search", params=params, timeout=common.TIMEOUT)
    r.raise_for_status()
    return [res["file"]["id"] for res in r.json().get("results", [])]


def evaluate(session, benchmark: list[dict], topk: int) -> list[dict]:
    rows = []
    for entry in benchmark:
        relevant = set(entry["relevant"])
        retrieved = run_query(session, entry["query"], entry.get("album_ids", []), topk)
        row = {
            "query": entry["query"],
            "category": entry.get("category", "uncategorised"),
            "num_relevant": len(relevant),
            "num_retrieved": len(retrieved),
            "P@5": common.precision_at_k(retrieved, relevant, 5),
            "P@10": common.precision_at_k(retrieved, relevant, 10),
            "R@10": common.recall_at_k(retrieved, relevant, 10),
            # Recall over the whole requested window (topK): did it find them at all,
            # not just in the top 10. Fairer for queries with large relevant sets.
            "R@K": common.recall_at_k(retrieved, relevant, len(retrieved)),
            "AP": common.average_precision(retrieved, relevant),
            "nDCG@10": common.ndcg_at_k(retrieved, relevant, 10),
            "RR": common.reciprocal_rank(retrieved, relevant),
        }
        rows.append(row)
        print(f"  [{row['category']:>12}] AP={row['AP']:.3f} P@5={row['P@5']:.2f} "
              f"R@10={row['R@10']:.2f} R@K={row['R@K']:.2f} rel={row['num_relevant']:>3}  "
              f"{entry['query'][:50]}")
    return rows


METRIC_KEYS = ["P@5", "P@10", "R@10", "R@K", "AP", "nDCG@10", "RR"]
DISPLAY = {"P@5": "P@5", "P@10": "P@10", "R@10": "R@10", "R@K": "R@K",
           "AP": "mAP", "nDCG@10": "nDCG@10", "RR": "MRR"}
LABELS = DISPLAY  # aggregate print names


def aggregate(rows: list[dict]) -> dict[str, float]:
    return {k: common.mean(r[k] for r in rows) for k in METRIC_KEYS}


def by_category(rows: list[dict]) -> dict[str, dict[str, float]]:
    cats: dict[str, list[dict]] = {}
    for r in rows:
        cats.setdefault(r["category"], []).append(r)
    return {c: aggregate(rs) for c, rs in sorted(cats.items())}


def write_csv(rows: list[dict], path: str) -> None:
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def write_tex(overall: dict, cats: dict, n: int, path: str) -> None:
    def fmt(m):
        return " & ".join(f"{m[k]:.3f}" for k in METRIC_KEYS)
    col_spec = "|l|" + "c|" * len(METRIC_KEYS)
    header = "\\textbf{Query set} & " + " & ".join(
        f"\\textbf{{{DISPLAY[k]}}}" for k in METRIC_KEYS) + " \\\\ [0.5ex]"
    lines = [
        "% auto-generated by eval/eval_semantic.py",
        f"\\begin{{tabular}}{{{col_spec}}}",
        "\\hline",
        header,
        "\\hline",
        f"All ({n} queries) & {fmt(overall)} \\\\",
        "\\hline",
    ]
    for cat, m in cats.items():
        lines.append(f"{cat} & {fmt(m)} \\\\")
        lines.append("\\hline")
    lines.append("\\end{tabular}")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def plot_categories(cats: dict, path: str) -> None:
    if not cats:
        return
    names = list(cats.keys())
    metrics = ["P@10", "R@10", "R@K", "nDCG@10"]
    x = range(len(names))
    width = 0.2
    plt.figure(figsize=(max(6, len(names) * 1.8), 4))
    for i, m in enumerate(metrics):
        plt.bar([xi + i * width for xi in x], [cats[n][m] for n in names],
                width=width, label=m)
    plt.xticks([xi + 1.5 * width for xi in x], names, rotation=15)
    plt.ylim(0, 1)
    plt.xlabel("Query category")
    plt.ylabel("Score")
    plt.title("Semantic search quality by query category")
    plt.legend()
    plt.tight_layout()
    plt.savefig(path)
    print(f"Wrote {path}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--benchmark", default="semantic_benchmark.json")
    ap.add_argument("--topk", type=int, default=50,
                    help="how many results to request per query (for the metric window)")
    args = ap.parse_args()

    with open(args.benchmark, encoding="utf-8") as f:
        benchmark = json.load(f)

    session = common.make_session()
    common.require_auth(session)
    print(f"Evaluating {len(benchmark)} queries (topK={args.topk}) ...")

    rows = evaluate(session, benchmark, args.topk)
    overall = aggregate(rows)
    cats = by_category(rows)

    print("\n=== Overall ===")
    for k in METRIC_KEYS:
        print(f"  {LABELS.get(k, k):>8}: {overall[k]:.3f}")

    write_csv(rows, os.path.join(common.out_dir(), "semantic_per_query.csv"))
    write_tex(overall, cats, len(rows), os.path.join(common.out_dir(), "semantic_metrics.tex"))
    plot_categories(cats, os.path.join(common.figs_dir(), "semantic_by_category.pdf"))
    print(f"\nTables/CSV in {common.out_dir()}")


if __name__ == "__main__":
    main()
