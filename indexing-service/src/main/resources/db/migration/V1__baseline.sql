-- Baseline schema for the tables owned by indexing-service.
-- Uses IF NOT EXISTS throughout so it applies cleanly both to fresh databases
-- and to databases whose tables were previously created by Hibernate auto-DDL.
-- (auth-service owns the users and Spring Session tables.)

CREATE TABLE IF NOT EXISTS albums (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drive_folder_id     VARCHAR(255) NOT NULL UNIQUE,
    title               VARCHAR(500) NOT NULL,
    enabled             BOOLEAN NOT NULL DEFAULT TRUE,
    deleted_in_drive    BOOLEAN NOT NULL DEFAULT FALSE,
    year                VARCHAR(10),
    indexing_faces      BOOLEAN NOT NULL DEFAULT FALSE,
    last_synced_at      TIMESTAMP(6) WITH TIME ZONE,
    last_indexed_at     TIMESTAMP(6) WITH TIME ZONE,
    face_indexed_at     TIMESTAMP(6) WITH TIME ZONE,
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_albums_drive_folder_id ON albums (drive_folder_id);
CREATE INDEX IF NOT EXISTS idx_albums_enabled ON albums (enabled);

CREATE TABLE IF NOT EXISTS media_items (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drive_file_id         VARCHAR(255) NOT NULL UNIQUE,
    album_id              BIGINT NOT NULL REFERENCES albums (id),
    filename              VARCHAR(500) NOT NULL,
    mime_type             VARCHAR(100) NOT NULL,
    size_bytes            BIGINT,
    drive_thumbnail_link  VARCHAR(1000),
    created_in_drive_at   TIMESTAMP(6) WITH TIME ZONE,
    modified_in_drive_at  TIMESTAMP(6) WITH TIME ZONE,
    last_seen_in_drive_at TIMESTAMP(6) WITH TIME ZONE,
    deleted_in_drive      BOOLEAN NOT NULL DEFAULT FALSE,
    indexing_status       VARCHAR(30) NOT NULL,
    faiss_indexed_at      TIMESTAMP(6) WITH TIME ZONE,
    indexing_error        VARCHAR(2000),
    created_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_media_drive_file_id ON media_items (drive_file_id);
CREATE INDEX IF NOT EXISTS idx_media_album_id ON media_items (album_id);
CREATE INDEX IF NOT EXISTS idx_media_deleted_in_drive ON media_items (deleted_in_drive);
CREATE INDEX IF NOT EXISTS idx_media_indexing_status ON media_items (indexing_status);

CREATE TABLE IF NOT EXISTS sync_runs (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                  VARCHAR(40) NOT NULL,
    status                VARCHAR(30) NOT NULL,
    target_album_drive_id VARCHAR(255),
    target_album_title    VARCHAR(500),
    -- No FK to users: that table is owned and created by auth-service.
    started_by_user_id    BIGINT,
    started_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at           TIMESTAMP(6) WITH TIME ZONE,
    albums_scanned        INTEGER NOT NULL DEFAULT 0,
    media_seen            INTEGER NOT NULL DEFAULT 0,
    media_created         INTEGER NOT NULL DEFAULT 0,
    media_updated         INTEGER NOT NULL DEFAULT 0,
    media_marked_deleted  INTEGER NOT NULL DEFAULT 0,
    media_indexed         INTEGER NOT NULL DEFAULT 0,
    media_failed          INTEGER NOT NULL DEFAULT 0,
    error_message         VARCHAR(4000),
    created_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sync_runs_status ON sync_runs (status);
CREATE INDEX IF NOT EXISTS idx_sync_runs_type ON sync_runs (type);
CREATE INDEX IF NOT EXISTS idx_sync_runs_started_at ON sync_runs (started_at);
