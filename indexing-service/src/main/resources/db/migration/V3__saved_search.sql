-- Saved searches: per-user history of a search's result photo IDs (ranked order),
-- powering "search within results" (refine) and recall of past searches.
-- Written/read by search-service; the schema lives here because indexing-service
-- owns the media_db schema (search-service runs with ddl-auto=validate).

CREATE TABLE IF NOT EXISTS saved_searches (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_email       VARCHAR(255) NOT NULL,
    search_type      VARCHAR(20) NOT NULL,
    query_text       VARCHAR(1000),
    album_ids        VARCHAR(2000),
    result_file_ids  TEXT NOT NULL,
    result_count     INTEGER NOT NULL,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_saved_searches_user ON saved_searches (user_email, created_at);
